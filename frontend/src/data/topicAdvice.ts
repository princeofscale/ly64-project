function normalizeTopicName(
  questionNumber: number,
  rawTopic: string,
  mappingKey: string
): { topicName: string; advice: string[] } {
  const mapping = TOPIC_ADVICE[mappingKey];
  if (mapping) {
    const entry = mapping[String(questionNumber)];
    if (entry) {
      return { topicName: entry.topic, advice: entry.advice };
    }
  }

  if (rawTopic) {
    const lowerTopic = rawTopic.toLowerCase();
    for (const rule of KEYWORD_FALLBACK) {
      if (rule.keywords.some(kw => lowerTopic.includes(kw))) {
        return { topicName: rule.topic, advice: rule.advice };
      }
    }
  }

  return {
    topicName: rawTopic || `Задание ${questionNumber}`,
    advice: ['Повторите материал по данной теме', 'Разберите аналогичные задания'],
  };
}

function getMappingKey(subject: string, examType: string): string {
  // Handle possible variations
  const subj = subject.toUpperCase();
  const exam = examType.toUpperCase();

  // Direct key
  const directKey = `${subj}_${exam}`;
  if (TOPIC_ADVICE[directKey]) return directKey;

  // Try common aliases
  if (exam === 'EGE_PROFILE') {
    const altKey = `${subj}_EGE_PROFILE`;
    if (TOPIC_ADVICE[altKey]) return altKey;
  }
  if (exam === 'EGE_BASE') {
    const altKey = `${subj}_EGE_BASE`;
    if (TOPIC_ADVICE[altKey]) return altKey;
  }

  // Fallback to subject_examType
  return directKey;
}

export function analyzeTestErrors(
  subject: string,
  examType: string,
  _grade: number,
  questions: AnalyzedQuestion[]
): ErrorAnalysisResult {
  const mappingKey = getMappingKey(subject, examType);

  // Group questions by normalized topic
  const topicMap = new Map<string, {
    questions: AnalyzedQuestion[];
    advice: string[];
  }>();

  for (const q of questions) {
    const { topicName, advice } = normalizeTopicName(q.number, q.topic, mappingKey);

    if (!topicMap.has(topicName)) {
      topicMap.set(topicName, { questions: [], advice });
    }
    topicMap.get(topicName)!.questions.push(q);
  }

  // Build topic groups (only those with at least one error)
  const topicGroups: TopicErrorGroup[] = [];
  const strongTopics: string[] = [];
  let totalCorrect = 0;

  for (const [topicName, data] of topicMap) {
    const total = data.questions.length;
    const correct = data.questions.filter(q => q.isCorrect).length;
    const accuracy = total > 0 ? Math.round((correct / total) * 100) : 0;
    totalCorrect += correct;

    const wrongQuestions = data.questions.filter(q => !q.isCorrect);

    if (wrongQuestions.length > 0) {
      topicGroups.push({
        topicName,
        wrongQuestions,
        totalInTopic: total,
        correctInTopic: correct,
        accuracy,
        advice: data.advice,
      });
    } else if (total >= 2 && accuracy >= 80) {
      strongTopics.push(topicName);
    } else if (total === 1 && accuracy === 100) {
      strongTopics.push(topicName);
    }
  }

  // Sort by accuracy ascending (worst first)
  topicGroups.sort((a, b) => a.accuracy - b.accuracy);

  return {
    totalCorrect,
    totalQuestions: questions.length,
    topicGroups,
    strongTopics,
  };
}
